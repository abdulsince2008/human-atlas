const KNOWLEDGE_BY_ID = new Map(CURATED_KNOWLEDGE.map((k) => [k.conceptId, k]));
const KNOWLEDGE_BY_NAME = new Map(
  CURATED_KNOWLEDGE.map((k) => [k.anatomicalName.toLowerCase(), k]),
);

export function lookupStructureKnowledge(
  conceptId: string,
  name: string,
  meshSystem?: SystemId,
): StructureKnowledge {
  const exact =
    KNOWLEDGE_BY_ID.get(conceptId) ??
    KNOWLEDGE_BY_NAME.get(name.toLowerCase());
  if (exact) return exact;

  const sys = meshSystem ?? 'skeletal';
  const canonical = canonicalSystemForMeshSystem(sys);
  const meshSysInfo = SYSTEMS.find((s) => s.id === sys);

  return {
    conceptId,
    anatomicalName: name,
    commonName: name,
    canonicalSystem: canonical.id,
    synonyms: [],
    location: {
      en: 'Detailed per-structure anatomical coordinates are not yet authored for this individual piece. Inspect its highlighted position directly inside the 3D model.',
    },
    mainFunction: {
      en: meshSysInfo?.description ?? canonical.description.en,
    },
    characteristics: [
      'Verified 3D geometry from BodyParts3D 4.0 mapped to the ' + canonical.name.en + '.',
      'Individual piece-level textbook notes are not yet curated for this structure; system-level context is shown above.',
    ],
    terminology: [],
    relatedConceptIds: canonical.featuredConceptIds.filter((id) => id !== conceptId).slice(0, 4),
    inModel: true,
    verifiedCurated: false,
  };
}
