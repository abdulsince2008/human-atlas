export function resolveReadingLinks(keys: (keyof typeof VERIFIED_SOURCES)[]): ExternalReadingLink[] {
  const uniqueKeys = Array.from(new Set(keys));
  return uniqueKeys.map((key) => {
    const src = VERIFIED_SOURCES[key];
    return {
      id: `read-${src.id}`,
      title: src.title,
      authorOrPublisher: src.authorOrPublisher,
      url: src.url,
      sectionCovered: src.sectionCovered,
      level: src.level,
      language: src.language,
      accessType: src.accessType,
      licence: src.licence,
      dateChecked: src.dateChecked,
      topicRelationship: src.topicRelationship,
      reviewStatus: 'source_checked',
    };
  });
}
